function renderInventoryCard(item) {
  return `<button class="invCard rarity-${item.rarity || "Common"} ${selectedInventoryItemId === item.id ? "selected" : ""}" onclick="selectInventoryItem('${item.id}')"><span class="itemName">${escapeHtml(item.name)}</span><span class="itemMeta">${escapeHtml(itemTypeLabel(item))} · ${escapeHtml(item.rarity || "Common")}</span><span class="itemStats">${escapeHtml(itemDescription(item))}</span></button>`;
}
function renderSelectedItem(item) {
  if (!item) return `<div class="itemDetail empty">Select loot to receive unsolicited opinions from the dungeon.</div>`;
  const actions = [];
  if (isEquippable(item)) actions.push(`<button class="itemBtn primary" onclick="equipItem('${item.id}')">Equip</button>`);
  if (item.type === "lootbox") actions.push(`<button class="itemBtn primary" onclick="openLootBox('${item.id}')">Open</button>`);
  actions.push(`<button class="itemBtn danger" onclick="discardItem('${item.id}')">Drop</button><button class="itemBtn" onclick="clearInventorySelection()">Close</button>`);
  return `<div class="itemDetail rarity-${item.rarity || "Common"}"><div class="itemName">${escapeHtml(item.name)}</div><div class="itemMeta">${escapeHtml(itemTypeLabel(item))} · ${escapeHtml(item.rarity || "Common")}</div><p>${escapeHtml(item.flavor || choose(FLAVOR_LINES))}</p><div class="itemMeta">${escapeHtml(itemDescription(item))}</div>${formatComparison(item)}<div class="itemActions">${actions.join("")}</div></div>`;
}
function selectInventoryItem(id) { selectedInventoryItemId = id; updateInventoryUI(); }
function clearInventorySelection() { selectedInventoryItemId = null; updateInventoryUI(); }
function updateInventoryUI() {
  const panel = document.getElementById("inventoryPanel"); if (!panel) return;
  const eq = document.getElementById("equipmentStats"), list = document.getElementById("inventoryList"), detail = document.getElementById("inventoryDetail");
  if (eq) eq.innerHTML = renderEquipmentStats();
  const selected = player.inventory.find(i => i.id === selectedInventoryItemId);
  if (detail) detail.innerHTML = renderSelectedItem(selected);
  if (!list) return;
  if (!player.inventory.length) { list.innerHTML = '<div class="invEmpty">Inventory empty. The dungeon recommends tasteful grave robbery.</div>'; return; }
  list.innerHTML = player.inventory.map(renderInventoryCard).join("");
}
