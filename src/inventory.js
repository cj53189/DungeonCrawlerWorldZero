function makeId(p = "item") { return `${p}_${Date.now()}_${Math.floor(Math.random() * 999999)}`; }
function choose(a) { return a[Math.floor(Math.random() * a.length)]; }
function rollRarity(force = false) { if (force) return Math.random() < 0.08 ? "Legendary" : "Rare"; const r = Math.random(); return r < 0.60 ? "Common" : r < 0.84 ? "Uncommon" : r < 0.96 ? "Rare" : r < 0.995 ? "Epic" : "Legendary"; }
function rarityPower(r) { return { Common: 1, Uncommon: 2, Rare: 3, Epic: 4, Legendary: 6 }[r] || 1; }
function escapeHtml(value) { return String(value ?? "").replace(/[&<>'"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "'": "&#39;", '"': "&quot;" }[c])); }
function getItemStats(item) { return { hp: 0, attack: 0, defense: 0, speed: 0, audience: 0, damage: 0, range: 0, cooldown: 0, ...(item?.stats || {}) }; }
function isEquippable(item) { return item && ["weapon", "armor", "trinket"].includes(item.type) && item.slot; }

function createItem({ type, slot = null, rarity = "Common", name, stats = {}, flavor = "", weaponId = null, amount = 0 }) {
  return { id: makeId(type), type, slot, rarity, name, stats, flavor: flavor || choose(FLAVOR_LINES), weaponId, amount };
}

function weaponDisplayName(def, rarity) {
  const names = {
    greatsword: ["Two-Handed Apology", "Greatsword of Overcompensation", "Executive Cleaver"],
    hammer: ["Percussive Negotiator", "Hammer of Audience Retention", "Compliance Mallet"],
    spear: ["Personal Space Enforcer", "Spear of Plausible Distance", "Pointy Viewer Engagement Tool"],
    bow: ["Coward's Content Launcher", "Bow of Remote Consequences", "Sponsored String Dispenser"]
  };
  return `${rarity} ${choose(names[def.id] || [def.name])}`;
}

function generateWeaponItem(forceRare = false) {
  const weaponId = choose(WEAPON_ORDER.filter(id => id !== "fists"));
  const def = WEAPON_DEFINITIONS[weaponId];
  const rarity = rollRarity(forceRare);
  const p = rarityPower(rarity);
  return createItem({
    type: "weapon",
    slot: "weapon",
    rarity,
    weaponId,
    name: weaponDisplayName(def, rarity),
    stats: { damage: def.damage + p * 2, range: def.range, cooldown: def.cooldown, attack: Math.max(0, p - 1) },
    flavor: `A ${def.name.toLowerCase()} template with extra dungeon confidence sprayed on. Please face camera three before swinging.`
  });
}

function generateGear(forceRare = false) {
  const slot = choose(["body", "offhand", "trinket"]);
  const rarity = rollRarity(forceRare);
  const p = rarityPower(rarity);
  const base = slot === "body" ? choose(ARMOR_BASES) : slot === "offhand" ? choose(OFFHAND_BASES) : choose(TRINKET_BASES);
  const stats = { hp: 0, attack: 0, defense: 0, speed: 0, audience: 0 };
  if (slot === "body") { stats.hp = p * 10; stats.defense = Math.max(1, Math.floor(p / 2)); }
  if (slot === "offhand") { stats.defense = p; stats.hp = p * 3; }
  if (slot === "trinket") { Math.random() < 0.5 ? stats.attack = p * 2 : stats.audience = p * 3; }
  if (Math.random() < 0.24) stats.hp += p * 3;
  if (Math.random() < 0.20) stats.attack += p;
  if (Math.random() < 0.15) stats.speed += p * 0.03;
  return createItem({ type: slot === "trinket" ? "trinket" : "armor", slot, rarity, name: `${rarity} ${choose(ITEM_PREFIXES)} ${base}`, stats });
}

function generateJunkItem() {
  return createItem({ type: "junk", rarity: "Common", name: `${choose(ITEM_PREFIXES)} ${choose(JUNK_BASES)}`, flavor: "No stats. No resale value. Huge potential as a prop in your downfall." });
}

function generateLootBox(forceRare = false) { const rarity = rollRarity(forceRare); return { id: makeId("box"), type: "lootbox", rarity, name: `${rarity} Prize Box`, opened: false, flavor: "Can only be opened in a safe room. The dungeon calls this responsible dopamine handling.", stats: {} }; }
function generateGoldItem(amount) { return { id: makeId("gold"), type: "gold", rarity: "Common", name: `${amount} Gold`, amount, stats: {}, flavor: "Currency: the original jump scare." }; }

function itemTypeLabel(item) { if (!item) return "Unknown"; if (item.type === "gold") return "Gold"; if (item.type === "lootbox") return "Loot Box"; return item.slot ? SLOT_LABELS[item.slot] : item.type.charAt(0).toUpperCase() + item.type.slice(1); }
function itemDescription(i) {
  if (!i) return "";
  if (i.type === "gold") return `${i.amount} gold. It jingles with poor decision-making.`;
  if (i.type === "lootbox") return "Can only be opened in a safe room.";
  const s = getItemStats(i);
  const b = [];
  if (s.damage) b.push(`${s.damage} DMG`);
  if (s.range) b.push(`${s.range} RNG`);
  if (s.cooldown) b.push(`${s.cooldown} CD`);
  if (s.hp) b.push(`+${s.hp} HP`);
  if (s.attack) b.push(`+${s.attack} ATK`);
  if (s.defense) b.push(`+${s.defense} DEF`);
  if (s.speed) b.push(`+${s.speed.toFixed(2)} SPD`);
  if (s.audience) b.push(`+${s.audience} Audience`);
  return b.join(" · ") || "Mostly decorative. The dungeon approves of pointless confidence.";
}

function addItem(item) {
  player.inventory.push(item);
  if (item.type === "lootbox") { stats.lootBoxesFound++; achievement("NEW LOOT BOX", `You found a ${item.name}. It can only be opened in a safe room.`, `box_${item.id}`); }
  else if (item.type !== "junk") { stats.gearFound++; achievement("NEW GEAR", `You found ${item.name}. ${itemDescription(item)}`, `gear_${item.id}`); }
  updateInventoryUI(); updateHUD();
}

function getEquippedComparable(item) { return item?.slot ? player.equipment[item.slot] : null; }
function formatComparison(item) {
  if (!isEquippable(item)) return "";
  const equipped = getEquippedComparable(item);
  const next = getItemStats(item);
  const current = getItemStats(equipped);
  const rows = [];
  const keys = item.slot === "weapon" ? [["damage", "DMG"], ["range", "RNG"], ["cooldown", "CD", true], ["attack", "ATK"]] : [["hp", "HP"], ["attack", "ATK"], ["defense", "DEF"], ["speed", "SPD"], ["audience", "Audience"]];
  for (const [key, label, lowerIsBetter] of keys) {
    if (!next[key] && !current[key]) continue;
    const diff = (next[key] || 0) - (current[key] || 0);
    const good = lowerIsBetter ? diff < 0 : diff > 0;
    const bad = lowerIsBetter ? diff > 0 : diff < 0;
    const cls = good ? "statUp" : bad ? "statDown" : "statSame";
    const sign = diff > 0 ? "+" : "";
    const value = key === "speed" ? diff.toFixed(2) : diff;
    rows.push(`<div class="compareRow ${cls}"><span>${label}</span><span>${current[key] || 0} → ${next[key] || 0}</span><strong>${sign}${value}</strong></div>`);
  }
  return `<div class="compareBox"><div class="compareTitle">Against ${equipped ? escapeHtml(equipped.name) : `empty ${SLOT_LABELS[item.slot]} slot`}</div>${rows.join("") || "<div class=\"itemMeta\">No stat movement. Emotionally devastating.</div>"}</div>`;
}

function equipItem(id) {
  const idx = player.inventory.findIndex(i => i.id === id); if (idx < 0) return;
  const item = player.inventory[idx]; if (!isEquippable(item)) return;
  const old = player.equipment[item.slot];
  player.equipment[item.slot] = item;
  player.inventory.splice(idx, 1);
  if (old) player.inventory.push(old);
  if (item.slot === "weapon") setPlayerWeapon(item.weaponId || "fists", false);
  selectedInventoryItemId = old ? old.id : null;
  recalcEquipmentStats(); achievement("EQUIPPED", `You equipped ${item.name}. ${itemDescription(item)}`, `equip_${item.id}`); updateInventoryUI(); updateHUD();
}

function openLootBox(id) {
  const idx = player.inventory.findIndex(i => i.id === id); if (idx < 0) return; const box = player.inventory[idx]; if (box.type !== "lootbox") return;
  if (!player.safe) { announcer("Loot boxes may only be opened in safe rooms. The dungeon believes in responsible dopamine distribution."); return; }
  player.inventory.splice(idx, 1); stats.lootBoxesOpened++; const coins = 8 + Math.floor(Math.random() * 16) + rarityPower(box.rarity) * 6; player.coins += coins;
  const gear = Math.random() < 0.42 ? generateWeaponItem(box.rarity === "Rare" || box.rarity === "Epic" || box.rarity === "Legendary") : generateGear(box.rarity === "Rare" || box.rarity === "Epic" || box.rarity === "Legendary");
  player.inventory.push(gear); stats.gearFound++;
  achievement("LOOT BOX OPENED", `You opened ${box.name} and received ${coins} gold and ${gear.name}. Pants-based civilization remains possible.`, `open_${box.id}`);
  if (!achievements.has("firstLootBoxOpen")) achievement("NEW ACHIEVEMENT: Delayed Gratification", "You waited until a safe room to open a box. Somewhere, an impulse-control researcher just shed a single tear.", "firstLootBoxOpen");
  updateInventoryUI(); updateHUD();
}
function discardItem(id) { const idx = player.inventory.findIndex(i => i.id === id); if (idx < 0) return; const [item] = player.inventory.splice(idx, 1); if (selectedInventoryItemId === id) selectedInventoryItemId = null; announcer(`You dropped ${item.name}. The dungeon has sold it to someone with lower standards.`); updateInventoryUI(); updateHUD(); }
function recalcEquipmentStats() {
  let hp = 0, atk = 0, spd = 0, def = 0, aud = 0;
  for (const item of Object.values(player.equipment)) { if (!item) continue; const s = getItemStats(item); hp += s.hp || item.hp || 0; atk += s.attack || item.attack || 0; spd += s.speed || item.speed || 0; def += s.defense || item.defense || 0; aud += s.audience || item.audience || 0; }
  const old = player.maxHp; player.maxHp = 100 + (player.level - 1) * 14 + hp; player.attackDamage = 20 + (player.level - 1) * 4 + atk; player.speed = player.baseSpeed + spd; player.defense = def; player.audienceBonus = aud; if (player.maxHp > old) player.hp += player.maxHp - old; player.hp = Math.min(player.hp, player.maxHp);
}
