function finalizeCorpseIfEmpty(corpse) { if (corpse.loot.length) return; corpse.looted = true; achievement(corpse.boss ? "BOSS CORPSE STRIPPED" : "CORPSE STRIPPED", `You emptied ${corpse.name}. The dungeon thanks you for keeping the arena tidy and emotionally awful.`, `loot_${corpse.id}`); closeLootPanel(); }
